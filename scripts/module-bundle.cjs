const fs = require('node:fs');
function wrapModule(file, id) {
  const source = fs.readFileSync(file, 'utf8');
  if (source.startsWith('// Module lifetime wrapper')) throw Error('Module bundle already wrapped');
  fs.writeFileSync(file, '// Module lifetime wrapper: generated by scripts/module-bundle.cjs\n' +
    `(function(start){if(globalThis.SuperModuleHost) SuperModuleHost.register(${JSON.stringify(id)},start);` +
    `else if(typeof document==='undefined')start();else chrome.storage.local.get({${JSON.stringify('superModules:'+id)}:true})` +
    `.then(values=>{if(values[${JSON.stringify('superModules:'+id)}]===true)start();});})(function(){\n` + source + '\n});\n');
}
module.exports = {wrapModule};
